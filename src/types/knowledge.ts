export interface KnowledgeDocument {
  id: string;
  title: string;
  source_type: string;
  classification: 'PUBLIC' | 'PROFESSIONAL' | 'CONFIDENTIAL' | 'PRIVATE';
  content: string;
  version: number;
  created_at: string;
  updated_at: string;
}

export interface KnowledgeChunk {
  id: string;
  document_id: string;
  chunk_index: number;
  content: string;
  /**
   * The embedding vector, 768 dimensions to match Gemini's output size.
   *
   * It is null until the embedding has been generated. It cannot be an empty
   * array, because a pgvector column only accepts a vector with exactly the
   * declared number of dimensions.
   */
  embedding: number[] | null;
  classification: 'PUBLIC' | 'PROFESSIONAL' | 'CONFIDENTIAL' | 'PRIVATE';
  metadata: Record<string, unknown>;
  created_at: string;
}

/**
 * Payload accepted when inserting a knowledge document.
 *
 * `id`, `created_at` and `updated_at` are generated by the database
 * (uuid default + now() defaults), so they are omitted from inserts.
 */
export type KnowledgeDocumentInsert = Omit<
  KnowledgeDocument,
  'id' | 'created_at' | 'updated_at'
>;

/**
 * Payload accepted when inserting a knowledge chunk.
 *
 * `id` and `created_at` are generated by the database, so they are omitted
 * from inserts. Supplying a fixed placeholder id would cause a primary key
 * collision as soon as a second chunk is written.
 */
export type KnowledgeChunkInsert = Omit<KnowledgeChunk, 'id' | 'created_at'>;
